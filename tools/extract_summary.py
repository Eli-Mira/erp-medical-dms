#!/usr/bin/env python3
"""
Phase 0 - targeted extraction of the summary/report sheets for business-rule
archaeology. READ-ONLY.

Produces docs/summary_extract.md - headers + formula/validation evidence,
with sheet + cell citations so downstream docs can reference exact locations.
"""

import glob
import os
import sys

import openpyxl

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = r"C:\Desktop\Huge system"
DOCS = os.path.join(ROOT, "docs")

# workbook -> sheet titles worth deep inspection
TARGETS = {
    "مبيعات 6 اكتوبر 2026.xlsx": [
        "الرئيسية", "رصيد الارصدة المباعة", "كامل الكمية",
        "مخزن الزهراء اكتوبر", "تحت التصريف",
    ],
    "مبيعات الدقهليه 2026.xlsx": [
        "الرئيسية", "المرتبات", "المبيعات الشهرية", "كامل الكمية", "مخزن المنزلة",
    ],
    "مبيعات الشرقية 2026.xlsx": ["الرئيسية", "المرتبات", "عهدة الشرقية"],
    "مبيعات الغربية  2026.xlsx": ["الرئيسية", "المرتبات", "كامل الكمية"],
    "مبيعات الفيوم 2026.xlsx": ["الرئيسية", "كامل الكمية", "تحت التصريف"],
    "الميزانية العمومية 2026.xlsx": [
        "الموازنه العامه", "الميزانيه", "الارباح والخسائر",
        "الايرادات", "التكاليف", "المصروفات", "النقديه", "العملاء",
    ],
    "حسابات خاصه.xlsx": ["اجمالى الحسابات", "الحاج علاء", "مصاريفى", "الشركة الجديدة"],
}

HEADER_ROWS = 5
MAX_COLS = 40
MAX_FORMULAS = 60

out = []
out.append("# Summary-sheet extraction (business-rule archaeology)\n")
out.append("> Auto-generated by `tools/extract_summary.py`. Shows header rows, formulas and")
out.append("> data-validation rules with exact sheet/cell citations. Interpretation is done by hand.\n")

for wb_name, sheets in TARGETS.items():
    path = os.path.join(ROOT, wb_name)
    if not os.path.exists(path):
        out.append(f"\n## {wb_name}\n\n_MISSING FILE_\n")
        continue
    wb = openpyxl.load_workbook(path, read_only=True, data_only=False, keep_links=False)
    out.append(f"\n## {wb_name}\n")
    for title in sheets:
        if title not in wb.sheetnames:
            out.append(f"\n### `{title}`\n\n_NOT FOUND_\n")
            continue
        ws = wb[title]
        ncols = min(ws.max_column or 1, MAX_COLS)
        out.append(f"\n### `{title}`  ({ws.max_row} x {ws.max_column})\n")
        out.append("**Header rows:**\n")
        out.append("```")
        for row in ws.iter_rows(min_row=1, max_row=min(HEADER_ROWS, ws.max_row or 1),
                                max_col=ncols, values_only=True):
            cells = [("" if v is None else str(v).replace("\n", " ")[:24]) for v in row]
            out.append(" | ".join(cells))
        out.append("```")

        formulas = []
        for row in ws.iter_rows(min_row=1, max_row=ws.max_row or 1,
                                max_col=ws.max_column or 1, values_only=False):
            for cell in row:
                v = cell.value
                if isinstance(v, str) and v.startswith("="):
                    formulas.append((cell.coordinate, v))
        if formulas:
            out.append(f"\n**Formula cells ({len(formulas)} total, showing {min(len(formulas), MAX_FORMULAS)}):**\n")
            out.append("```")
            for coord, f in formulas[:MAX_FORMULAS]:
                out.append(f"{coord}: {f}")
            out.append("```")

        try:
            dvs = list(ws.data_validations.dataValidation or [])
        except Exception:
            dvs = []
        if dvs:
            out.append("\n**Data validations:**\n")
            out.append("```")
            for dv in dvs[:20]:
                out.append(f"{dv.type}  sqref={dv.sqref}  f1={dv.formula1}")
            out.append("```")
    wb.close()
    print(f"done {wb_name}", flush=True)

with open(os.path.join(DOCS, "summary_extract.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("WROTE docs/summary_extract.md")
