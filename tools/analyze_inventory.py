#!/usr/bin/env python3
"""
Phase 0 - analysis over inventory.json.

READ-ONLY on sources. Produces:
  docs/inventory_raw.md      - human-readable structural summary
  docs/analysis.json         - derived signals for doc authoring
     * sheet-name index + cross-workbook duplicates
     * placeholder/unnamed sheets
     * per-sheet formula presence
     * header fingerprints per workbook (for column dictionary)
"""

import json
import os
import re
import sys
from collections import Counter, defaultdict

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = r"C:\Desktop\Huge system"
DOCS = os.path.join(ROOT, "docs")

with open(os.path.join(DOCS, "inventory.json"), encoding="utf-8") as f:
    inv = json.load(f)

PLACEHOLDER = re.compile(r"^(ورقة\d|Sheet\d+|اخر ورقة|ورقة1)\b")

name_index = defaultdict(list)
placeholder = []
analysis_files = []

for wbf in inv["files"]:
    sheets_meta = []
    for sh in wbf["sheets"]:
        t = sh.get("title", "")
        name_index[t].append(wbf["file"])
        if PLACEHOLDER.match(t) or t.strip() in ("Sheet1", "Sheet2", "اخر ورقة"):
            placeholder.append((wbf["file"], t, sh.get("max_row"), sh.get("max_col")))
        sheets_meta.append({
            "title": t,
            "state": sh.get("state"),
            "max_row": sh.get("max_row"),
            "max_col": sh.get("max_col"),
            "nonempty_rows": sh.get("nonempty_rows"),
            "has_formulas": sh.get("has_formulas"),
            "formula_total": sh.get("formula_total"),
            "merged_count": sh.get("merged_count"),
            "dv_count": len(sh.get("data_validations", [])),
            "header_rows_sample": sh.get("header_rows_sample", []),
            "columns": sh.get("columns", []),
        })
    analysis_files.append({"file": wbf["file"], "sheet_count": wbf["sheet_count"], "sheets": sheets_meta})

dupes = {k: v for k, v in name_index.items() if len(v) > 1}

analysis = {
    "source_root": inv["source_root"],
    "generated_at": inv["generated_at"],
    "total_workbooks": len(inv["files"]),
    "total_sheets": sum(f["sheet_count"] for f in inv["files"]),
    "cross_workbook_sheet_duplicates": dupes,
    "placeholder_sheets": placeholder,
    "files": analysis_files,
}

with open(os.path.join(DOCS, "analysis.json"), "w", encoding="utf-8") as f:
    json.dump(analysis, f, ensure_ascii=False, indent=1)

# ---- human readable ----
out = []
out.append("# Excel Structural Inventory (raw)\n")
out.append(f"Generated: {inv['generated_at']}\n")
out.append(f"Source root: `{inv['source_root']}`\n")
out.append(f"Workbooks: **{len(inv['files'])}**  |  Sheets: **{sum(f['sheet_count'] for f in inv['files'])}**\n")
out.append("\n> Auto-generated by `tools/analyze_inventory.py`. Every figure is mechanical, not interpretive.\n")

for wbf in inv["files"]:
    out.append(f"\n## {wbf['file']}\n")
    out.append(f"- Size: {wbf['size_bytes']:,} bytes")
    out.append(f"- SHA-256: `{wbf['sha256']}`")
    out.append(f"- Sheets: {wbf['sheet_count']}  |  Defined names: {len(wbf['defined_names'])}  |  External links: {len(wbf['external_links'])}")
    out.append("\n| # | Sheet | State | Rows x Cols | Non-empty rows | Formulas | Merged | Validations |")
    out.append("|---|-------|-------|-------------|----------------|----------|--------|-------------|")
    for i, sh in enumerate(wbf["sheets"], 1):
        if "error" in sh:
            out.append(f"| {i} | {sh['title']} | ERR | - | - | - | - | {sh['error']} |")
            continue
        out.append(f"| {i} | {sh['title']} | {sh['state']} | {sh['max_row']} x {sh['max_col']} | "
                   f"{sh['nonempty_rows']} | {sh['formula_total']} | {sh['merged_count']} | "
                   f"{len(sh.get('data_validations', []))} |")

out.append("\n## Cross-workbook sheet-name duplicates\n")
out.append(f"{len(dupes)} names appear in more than one workbook.\n")
out.append("\n| Sheet name | Workbooks |")
out.append("|---|---|")
for k in sorted(dupes, key=lambda x: -len(dupes[x])):
    out.append(f"| {k} | {', '.join(dupes[k])} |")

out.append("\n## Placeholder / unnamed sheets\n")
out.append(f"{len(placeholder)} sheets match placeholder patterns.\n")
out.append("\n| Workbook | Sheet | Rows x Cols |")
out.append("|---|---|---|")
for wb, t, r, c in placeholder:
    out.append(f"| {wb} | {t} | {r} x {c} |")

with open(os.path.join(DOCS, "inventory_raw.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")

print("WROTE docs/analysis.json and docs/inventory_raw.md")
print(f"duplicate sheet names: {len(dupes)}")
print(f"placeholder sheets: {len(placeholder)}")
